import { chromium, BASE, PROTOTYPE, prepare } from './lib.mjs'
const browser = await chromium.launch()
const log = (...a) => console.log(...a)

// Phone menu.
const phone = await browser.newPage({ viewport: { width: 390, height: 844 }, ignoreHTTPSErrors: true })
await prepare(phone.context())
await phone.goto(BASE + '/', { waitUntil: 'networkidle' })
const burger = phone.locator('.rj-nav__burger')
log('menu closed:', await burger.getAttribute('aria-expanded'), await phone.locator('#rj-nav-panel').isHidden(), '| label:', await burger.locator('.screen-reader-text').textContent())
await burger.click()
log('menu open:', await burger.getAttribute('aria-expanded'), await phone.locator('#rj-nav-panel').isVisible(), '| label:', await burger.locator('.screen-reader-text').textContent())
await phone.keyboard.press('Escape')
log('after Escape:', await burger.getAttribute('aria-expanded'), '| focus on burger:', await phone.evaluate(() => document.activeElement?.classList.contains('rj-nav__burger')))
await burger.click()
await phone.locator('#rj-nav-panel a', { hasText: 'Encargos' }).click()
await phone.waitForLoadState('networkidle')
log('navigated to:', new URL(phone.url()).pathname, '| current link:', await phone.locator('.rj-nav__links a[aria-current="page"]').textContent())

// Keyboard: skip link, motion toggle, gallery.
const desk = await browser.newPage({ viewport: { width: 1440, height: 900 }, ignoreHTTPSErrors: true })
await prepare(desk.context())
await desk.goto(BASE + '/', { waitUntil: 'networkidle' })
await desk.keyboard.press('Tab')
log('first tab stop:', await desk.evaluate(() => `${ document.activeElement.textContent } visible=${ document.activeElement.getBoundingClientRect().top >= 0 }`))
await desk.keyboard.press('Tab')
log('second tab stop:', await desk.evaluate(() => document.activeElement.textContent))
await desk.keyboard.press('Enter')
log('motion after toggle:', await desk.evaluate(() => [ document.documentElement.dataset.motion, document.querySelector('.rj-motion-toggle').getAttribute('aria-pressed'), getComputedStyle(document.querySelector('.rj-ticker__rail')).animationPlayState, localStorage.getItem('rj-motion') ]))
await desk.reload({ waitUntil: 'networkidle' })
log('motion after reload:', await desk.evaluate(() => [ document.documentElement.dataset.motion, document.querySelector('.rj-motion-toggle').getAttribute('aria-pressed') ]))
await desk.locator('.rj-motion-toggle').focus(); await desk.keyboard.press('Enter')
log('motion resumed:', await desk.evaluate(() => [ document.documentElement.dataset.motion ?? 'none', localStorage.getItem('rj-motion') ]))

await desk.locator('.rj-gallery__stage').focus()
await desk.keyboard.press('ArrowRight')
await desk.waitForTimeout(1500)
log('gallery after →:', await desk.locator('.rj-gallery__caption').textContent(), '| current item:', await desk.evaluate(() => [ ...document.querySelectorAll('.rj-gallery__item') ].findIndex(i => i.getAttribute('aria-current') === 'true')))
await desk.locator('.rj-gallery__prev').click(); await desk.locator('.rj-gallery__prev').click()
await desk.waitForTimeout(1500)
log('gallery after ← ←:', await desk.locator('.rj-gallery__caption').textContent())
await browser.close()
