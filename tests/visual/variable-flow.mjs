import { chromium, BASE, PROTOTYPE, prepare } from './lib.mjs'
const browser = await chromium.launch()
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, ignoreHTTPSErrors: true, reducedMotion: 'reduce' })
await prepare(context)
const page = await context.newPage()
const errors = []
page.on('pageerror', e => errors.push(e.message))
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
await page.goto(BASE + '/producto/caja-de-alfajores/', { waitUntil: 'networkidle' })
console.log('scripts:', await page.evaluate(() => [ ...document.scripts ].map(s => s.src.split('/').pop().split('?')[0]).filter(Boolean).join(', ')))
await page.locator('select[name="attribute_tamano"]').selectOption('Docena')
await page.waitForTimeout(500)
console.log('variation price:', (await page.locator('.woocommerce-variation-price').textContent()).trim())
await page.evaluate(() => { document.querySelector('.rj-nav').style.position = 'relative' })
await page.screenshot({ path: 'output/variable.png', clip: { x: 0, y: 0, width: 1440, height: 900 } })
await page.locator('.single_add_to_cart_button').click()
await page.waitForLoadState('networkidle')
console.log('after add:', new URL(page.url()).pathname, '| header:', await page.locator('.rj-nav__cta').textContent())
await page.goto(BASE + '/carrito/', { waitUntil: 'networkidle' })
await page.locator('.wc-block-cart__submit-button').waitFor()
const href = await page.locator('.wc-block-cart__submit-button').getAttribute('href')
console.log('message:\n' + decodeURIComponent(href.split('?text=')[1]))
console.log(errors.length ? 'errors:\n' + errors.join('\n') : 'no console errors')
await browser.close()
